const questionsPath = 'server/data/questions.json';
const questions = JSON.parse(await readFile(questionsPath, 'utf8'));
const missing = { questions: new Set(), options: new Set(), explanations: new Set() };
for (const q of questions) {
  if (qT[q.textHe]) q.textAr = qT[q.textHe]; else missing.questions.add(q.textHe);
  q.optionsAr = (q.optionsHe || []).map(opt => optT[opt] || (missing.options.add(opt), opt));
  if (expT[q.explanationHe]) q.explanationAr = expT[q.explanationHe]; else missing.explanations.add(q.explanationHe);
}
await writeFile(questionsPath, JSON.stringify(questions, null, 2));

